"""The merged dataset as the addon's Lua files.

Data/<class>.lua   KeyLootMasterData["paladin"]["protection"]["mplus"]["head"] = { {item, share, sample}, ... }
Data/Drops.lua     KeyLootMasterDrops[itemId] = { {kind, instance, instanceName, encounter, encounterName}, ... }
Data/Stats.lua     KeyLootMasterStats[class][spec] = { n = players, c = {rating, percent}, h, m, v, leech, avoidance, speed }
Data/Meta.lua      KeyLootMasterMeta = { generated = "...", sources = { ... }, top = N }

One file per class keeps each load small. The output is deterministic: the
same dataset gives the same bytes, so a day without new data changes nothing.
"""

from __future__ import annotations

from .merge import top_per_slot
from .model import STAT_KEYS

HEADER = "-- Generated by the KeyLootMaster pipeline. Do not edit.\n"


def quote(text) -> str:
    escaped = str(text).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return '"' + escaped + '"'


def key(text) -> str:
    return "[" + quote(text) + "]"


def class_files(dataset: dict, top: int) -> dict:
    """File name -> text, one file per class."""
    grouped = top_per_slot(dataset.get("entries", []), top)
    by_class: dict = {}
    for (cls, spec, content, slot), rows in grouped.items():
        by_class.setdefault(cls, {}).setdefault(spec, {}).setdefault(content, {})[slot] = rows
    files = {}
    for cls in sorted(by_class):
        lines = [HEADER, "KeyLootMasterData = KeyLootMasterData or {}\n",
                 "KeyLootMasterData[" + quote(cls) + "] = {\n"]
        for spec in sorted(by_class[cls]):
            lines.append("  " + key(spec) + " = {\n")
            for content in sorted(by_class[cls][spec]):
                lines.append("    " + key(content) + " = {\n")
                for slot in sorted(by_class[cls][spec][content]):
                    rows = by_class[cls][spec][content][slot]
                    cells = ", ".join("{%d, %s, %d}" % (r["item"], r["share"], r["sample"]) for r in rows)
                    lines.append("      " + key(slot) + " = { " + cells + " },\n")
                lines.append("    },\n")
            lines.append("  },\n")
        lines.append("}\n")
        files[cls + ".lua"] = "".join(lines)
    return files


def drops_file(dataset: dict) -> str:
    by_item: dict = {}
    for drop in dataset.get("drops", []):
        by_item.setdefault(drop["item"], []).append(drop)
    lines = [HEADER, "KeyLootMasterDrops = {\n"]
    for item in sorted(by_item):
        cells = ", ".join(
            "{kind = %s, instance = %s, instanceName = %s, encounter = %s, encounterName = %s}" % (
                quote(d["kind"]), d["instance"], quote(d["instance_name"]),
                d["encounter"], quote(d["encounter_name"]))
            for d in by_item[item])
        lines.append("  [%d] = { %s },\n" % (item, cells))
    lines.append("}\n")
    return "".join(lines)


def shown_items(dataset: dict, top: int) -> set:
    """The items that appear in a class file (the most worn per slot)."""
    return {row["item"] for rows in top_per_slot(dataset.get("entries", []), top).values() for row in rows}


def items_file(dataset: dict, top: int) -> str:
    """KeyLootMasterItems[itemId] = { s = "ch", l = ilvl, t = true } for the shown items."""
    shown = shown_items(dataset, top)
    lines = [HEADER, "KeyLootMasterItems = {\n"]
    for item in dataset.get("items", []):
        if item["item"] not in shown:
            continue
        fields = ['s = ' + quote(item["stats"]), "l = %d" % item["ilvl"]]
        if item["tier"]:
            fields.append("t = true")
        lines.append("  [%d] = { %s },\n" % (item["item"], ", ".join(fields)))
    lines.append("}\n")
    return "".join(lines)


def specs_file(dataset: dict) -> str:
    """KeyLootMasterSpecs[specId] = { classKey, specKey }: the game's ids to our names."""
    lines = [HEADER, "KeyLootMasterSpecs = {\n"]
    for spec_id, (cls, spec) in sorted(dataset.get("specs", {}).items(), key=lambda kv: int(kv[0])):
        lines.append("  [%s] = { %s, %s },\n" % (spec_id, quote(cls), quote(spec)))
    lines.append("}\n")
    return "".join(lines)


LOAD_ORDER = ("Meta.lua", "Specs.lua", "Drops.lua", "Items.lua", "Stats.lua", "Bonus.lua")


def manifest(lua_files: list) -> str:
    """Data.xml: the order the client loads the generated files in (shared tables first)."""
    names = sorted(lua_files, key=lambda n: (LOAD_ORDER.index(n) if n in LOAD_ORDER else len(LOAD_ORDER), n))
    scripts = "".join('  <Script file="%s"/>\n' % n for n in names if n.endswith(".lua"))
    return ('<Ui xmlns="http://www.blizzard.com/wow/ui/">\n'
            "  <!-- Generated by the KeyLootMaster pipeline. Do not edit. -->\n" + scripts + "</Ui>\n")


def bonus_file(bonus: dict) -> str:
    """Data/Bonus.lua: KeyLootMasterBonus[levelDelta] = the bonus list ID that moves an item's level by it."""
    rows = "".join("  [%d] = %d,\n" % (int(delta), bonus[delta]) for delta in sorted(bonus, key=int))
    return HEADER + "KeyLootMasterBonus = {\n" + rows + "}\n"


def stats_file(dataset: dict) -> str:
    """Data/Stats.lua: the average stats of the best players per class and specialization."""
    by_class: dict = {}
    for record in dataset.get("stats", []):
        by_class.setdefault(record["class"], {})[record["spec"]] = record
    lines = [HEADER, "KeyLootMasterStats = {\n"]
    for cls in sorted(by_class):
        lines.append("  " + key(cls) + " = {\n")
        for spec in sorted(by_class[cls]):
            record = by_class[cls][spec]
            cells = ", ".join("%s = {%d, %.1f}" % (stat, round(record[stat][0]), record[stat][1]) for stat in STAT_KEYS)
            lines.append("    " + key(spec) + " = { n = %d, %s },\n" % (record["n"], cells))
        lines.append("  },\n")
    lines.append("}\n")
    return "".join(lines)


def meta_file(dataset: dict, top: int) -> str:
    sources = ", ".join(quote(s) for s in dataset.get("sources", []))
    return (HEADER + "KeyLootMasterMeta = {\n"
            "  generated = " + quote(dataset["generated"]) + ",\n"
            "  sources = { " + sources + " },\n"
            "  top = " + str(top) + ",\n}\n")
